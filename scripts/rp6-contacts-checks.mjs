import assert from 'node:assert/strict'
import { join } from 'node:path'

export async function checkContacts({ page, sql, temp, stage }) {
  const facts = () => sql("SELECT (SELECT COUNT(*) FROM events)||':'||(SELECT COUNT(*) FROM agent_knowledge)||':'||(SELECT current_world_time FROM world_clocks WHERE instance_id='inst_m2_t09' AND branch_id='br_main')")
  const before = facts()
  const bookmark = await page.evaluate(() => localStorage.getItem('corerp.play.v1'))
  const response = page.waitForResponse(r => r.url().endsWith('/rp/contacts/read'))
  const opener = page.getByRole('button', { name: '通讯录', exact: true })
  const dialog = page.getByRole('dialog', { name: '通讯录', exact: true })
  await opener.click()
  const { data } = await (await response).json()
  const known = sql("SELECT DISTINCT k.subject_agent_id FROM agent_knowledge k JOIN rp_identity_familiarity f ON f.observer_agent_id=k.observer_agent_id AND f.subject_agent_id=k.subject_agent_id WHERE k.observer_agent_id='entity_m2_rp_lin' AND k.subject_agent_id<>'entity_m2_rp_lin' AND json_extract(k.claim_payload,'$.claim_type') IN ('agent_presence','speaker_said') ORDER BY k.subject_agent_id").split('\n').filter(Boolean)
  assert.deepEqual(data.contacts.map(c => c.entity_id), known)
  for (const contact of data.contacts) {
    assert.deepEqual(Object.keys(contact).sort(), ['display_name', 'entity_id', 'last_known_world_time'])
    await dialog.getByText(contact.display_name, { exact: true }).waitFor()
  }
  if (!known.length) await dialog.getByText('还没有记下认识的人。亲历的相遇会留在这里。', { exact: true }).waitFor()
  if (stage === 'entry') assert.ok(!known.includes('entity_m2_bo'), 'no population directory before encounter')
  else assert.ok(data.contacts.some(c => c.display_name === 'Cai'), 'past off-scene contact remains known after restart')
  await dialog.getByRole('button', { name: '关闭通讯录' }).focus()
  await page.keyboard.press('Shift+Tab')
  assert.equal(await dialog.evaluate(el => el.contains(document.activeElement)), true)
  assert.equal(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), true)
  await page.screenshot({ path: join(temp, `contacts-${stage}-mobile.png`) })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: join(temp, `contacts-${stage}-desktop.png`) })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('**/api/v1/rp/contacts/read', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '测试读取暂不可用' } }) }), { times: 1 })
  await dialog.getByRole('button', { name: '重新翻阅' }).click()
  await dialog.getByRole('alert').waitFor()
  assert.match(await dialog.getByRole('alert').innerText(), /上次读取/)
  assert.equal(await dialog.locator('li').count(), known.length, 'failed refresh preserves labeled old record')
  await dialog.getByRole('button', { name: '重新翻阅' }).click()
  await dialog.getByRole('alert').waitFor({ state: 'hidden' })
  await dialog.getByRole('status').waitFor({ state: 'hidden' })
  await page.keyboard.press('Escape')
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(await opener.evaluate(el => document.activeElement === el), true)
  assert.equal(facts(), before)
  assert.equal(await page.evaluate(() => localStorage.getItem('corerp.play.v1')), bookmark)
  await page.evaluate(() => window.scrollTo({ top: document.documentElement.scrollHeight }))
  console.log(JSON.stringify({ contacts: 'PASS', stage, count: known.length, checks: ['actual own knowledge matches SQLite', 'minimal private-data contract', 'empty/known history', 'keyboard/Escape', 'read error/retry retains labeled snapshot', 'no world/knowledge/bookmark mutation'] }))
}
