import assert from 'node:assert/strict'
import { join } from 'node:path'
import { openPlayBusiness, scrollPlayToEnd } from './play-ui-helpers.mjs'

export async function checkWork({ page, sql, temp, stage, expectedJobs }) {
  const facts = () => sql("SELECT (SELECT COUNT(*) FROM events)||':'||(SELECT COUNT(*) FROM agent_knowledge)||':'||(SELECT current_world_time FROM world_clocks WHERE instance_id='inst_m2_t09' AND branch_id='br_main')")
  const before = facts()
  const bookmark = await page.evaluate(() => localStorage.getItem('corerp.play.v1'))
  const response = page.waitForResponse(r => r.url().endsWith('/rp/work/read'))
  const opener = page.getByRole('button', { name: '行动与功能', exact: true })
  const dialog = page.getByRole('dialog', { name: '工作信息', exact: true })
  await openPlayBusiness(page, '工作信息')
  const { data } = await (await response).json()
  assert.ok(data, 'real service must return work data')
  assert.equal(data.jobs.length, expectedJobs)
  const ownSchedule = sql("SELECT s.schedule_id FROM agent_schedule_entries s JOIN scheduler_items q ON q.scheduler_item_id=s.scheduler_item_id WHERE s.agent_id='entity_m2_rp_lin' AND s.status='active' AND q.status='pending' AND q.world_time>=(SELECT current_world_time FROM world_clocks WHERE instance_id='inst_m2_t09' AND branch_id='br_main') ORDER BY q.world_time,s.declared_priority,s.schedule_id LIMIT 21").split('\n').filter(Boolean)
  assert.deepEqual(data.appointments.map(a => a.schedule_id), ownSchedule.slice(0, 20))
  assert.equal(data.more_appointments, ownSchedule.length > 20)
  if (!expectedJobs) await dialog.getByText('没有查到当前有效的工作合同。', { exact: true }).waitFor()
  for (const job of data.jobs) {
    assert.deepEqual(Object.keys(job).sort(), ['contract_id', 'currency_id', 'currency_scale', 'currency_symbol', 'employer_name', 'pay_period_days', 'status', 'wage_minor', 'workplace_name'])
    const wage = sql(`SELECT c.unit_rate_minor FROM m2_wage_participation_splits s JOIN m2_cohort_contracts c ON c.contract_id=s.contract_id WHERE s.entity_id='entity_m2_rp_lin' AND c.contract_id='${job.contract_id.replaceAll("'", "''")}'`)
    assert.equal(job.wage_minor, wage, 'actual conserved participation wage, not a UI fixture')
    assert.equal(job.pay_period_days, 0, 'legacy contract has no declared pay period')
    await dialog.getByText('计薪周期未登记，请以合同结算为准。', { exact: true }).waitFor()
  }
  await dialog.getByText('约定报酬不是已到账收入；实际结算和钱包余额以已发生的记录为准。', { exact: true }).waitFor()
  await dialog.getByRole('status').waitFor({ state: 'hidden' })
  assert.equal(await dialog.locator('li').count(), data.appointments.length)
  await dialog.getByRole('button', { name: '关闭工作信息' }).focus()
  await page.keyboard.press('Shift+Tab')
  assert.equal(await dialog.evaluate(el => el.contains(document.activeElement)), true)
  // Focus may scroll to the footer; photograph the actual top-level hierarchy.
  await dialog.evaluate(el => { el.scrollTop = 0 })
  assert.equal(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), true)
  await page.screenshot({ path: join(temp, `work-${stage}-mobile.png`) })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: join(temp, `work-${stage}-desktop.png`) })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('**/api/v1/rp/work/read', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '测试读取暂不可用' } }) }), { times: 1 })
  await dialog.getByRole('button', { name: '重新查看工作' }).click()
  await dialog.getByRole('alert').waitFor()
  assert.match(await dialog.getByRole('alert').innerText(), /上次读取/)
  assert.equal(await dialog.locator('.job').count(), expectedJobs)
  await dialog.getByRole('button', { name: '重新查看工作' }).click()
  await dialog.getByRole('alert').waitFor({ state: 'hidden' })
  await dialog.getByRole('status').waitFor({ state: 'hidden' })
  await page.keyboard.press('Escape')
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(await opener.evaluate(el => document.activeElement === el), true)
  assert.equal(facts(), before, 'work read cannot advance time or write events/knowledge')
  assert.equal(await page.evaluate(() => localStorage.getItem('corerp.play.v1')), bookmark)
  await scrollPlayToEnd(page)
  console.log(JSON.stringify({ work: 'PASS', stage, jobs: data.jobs.length, appointments: data.appointments.length, checks: ['real own contract and schedule', 'exact wage string', 'no invented pay period', 'keyboard/Escape', 'error/retry snapshot', 'read-only world/bookmark'] }))
  return data
}
