那人进来先不说话，绕着铺子走了一圈，手指在案台上的铁屑里划过一道，然后才问：「六十件精铁犁头，一个月，赶得出么？」

何图正在给一把镰刀淬火。他把镰刀插进水里，嘶啦一声白汽腾起来，隔着汽他问：「急？」

「宗门度支的额度四月一号就换月。」执事说，「换月之前不结，就得等下个季度。」

何图就知道这笔单子不是「急」，是「卡在一条线上」。他把镰刀提起来看了看刃口的纹，说：「赶得出。但不是六十件都一个模子——外门的地块我听说过，南坡偏黏，北坡偏砂，犁头开刃的角度不一样。」

